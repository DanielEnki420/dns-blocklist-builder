#!/usr/bin/env bash
# tests/test-setup-pi5.sh - tests for setup-pi5.sh and the update script it writes
#
#   bash tests/test-setup-pi5.sh
#
# setup-pi5.sh needs root and changes the system, so it never runs here as a
# whole. The tests take single functions out of it and run the update script it
# generates against a throwaway clone: real git, real generate-lists.js (needs
# node), fake pihole, docker, curl, apt-get and systemctl. Nothing leaves the
# temporary directory; Telegram messages end up in a log file.
# The settings in ( … ) are read by functions loaded with eval, in a subshell on
# purpose; single quotes keep $ literal for the fakes and the expected text.
# shellcheck disable=SC2016,SC2030,SC2031,SC2034
set -uo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
setup=$root/setup-pi5.sh
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
pass=0 nfail=0

ok_() { pass=$((pass + 1)); printf '  ok    %s\n' "$1"; }
fail_() { nfail=$((nfail + 1)); printf '  FAIL  %s\n' "$1"; [ -z "${2:-}" ] || printf '        %s\n' "$2"; }
# same NAME ACTUAL EXPECTED
same() { if [ "$2" = "$3" ]; then ok_ "$1"; else fail_ "$1" "got '$2', expected '$3'"; fi; }
# has NAME FILE TEXT - FILE contains TEXT
has() { if grep -qF -- "$3" "$2" 2>/dev/null; then ok_ "$1"; else fail_ "$1" "'$3' not in $(basename "$2"): $(head -c 300 "$2" 2>/dev/null)"; fi; }
# lacks NAME FILE TEXT - FILE does not contain TEXT
lacks() { if grep -qF -- "$3" "$2" 2>/dev/null; then fail_ "$1" "'$3' found in $(basename "$2")"; else ok_ "$1"; fi; }

command -v node >/dev/null || { echo "node is needed (generate-lists.js)"; exit 2; }
# The scripts call a host Pi-hole directly (pihole -g, sqlite3 on its gravity.db);
# there is no fake for that, so never run where a real one is installed.
if command -v pihole >/dev/null; then
  echo "Pi-hole is installed here ($(command -v pihole)); the tests would call it. Run them on another machine."
  exit 2
fi
G=(git -c user.name=test -c user.email=test@example.com -c commit.gpgsign=false)

# fn NAME - the function NAME from setup-pi5.sh as text; a brace at the start
# of a line inside the update script's heredoc does not end it
fn() {
  awk -v n="$1" '
    $0 ~ "^" n "\\(\\) \\{" { on = 1 }
    on { print }
    on && /<</ && /UPDATESCRIPT.$/ { here = 1 }
    on && /^UPDATESCRIPT$/ { here = 0; next }
    on && !here && /^}$/ { exit }
  ' "$setup"
}
eval "$(grep '^LIST_URL=' "$setup")"
# a placeholder that matches nothing, so the URL checks fail instead of the run
[ -n "${LIST_URL:-}" ] || LIST_URL="(setup-pi5.sh defines no LIST_URL)"
ok() { echo "ok: $*"; }
warn() { echo "warn: $*"; }
info() { echo "info: $*"; }
die() { echo "die: $*"; exit 1; }

# --- fakes -----------------------------------------------------------------
bin=$tmp/bin log=$tmp/log
mkdir -p "$bin" "$tmp/fakenode"
cat >"$bin/curl" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$*" >>"$FAKE_LOG/curl.log"
EOF
cat >"$bin/docker" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$*" >>"$FAKE_LOG/docker.log"
if [ "$1" = ps ]; then printf '%s' "${FAKE_CONTAINERS:-}" | tr ' ' '\n'; fi
exit 0
EOF
for t in apt-get systemctl; do
  printf '#!/usr/bin/env bash\nprintf "%%s\\n" "$*" >>"$FAKE_LOG/%s.log"\n' "$t" >"$bin/$t"
done
cat >"$tmp/fakenode/node" <<'EOF'
#!/usr/bin/env bash
echo "$FAKE_NODE_VERSION"
EOF
chmod +x "$bin"/* "$tmp/fakenode/node"
export FAKE_LOG=$log

# fresh [SKIP_PIHOLE] - an install the way it looks in its second week:
#   upstream: a clone of this repository whose lists say "Generated: 2000-01-01"
#   install:  cloned from it, update script written by setup-pi5.sh, and lists/
#             regenerated by last week's run (today's date, so they differ)
#   upstream again: the weekly action committed new lists
fresh() {
  rm -rf "$tmp/up" "$tmp/inst" "$log"
  mkdir -p "$log"
  git clone -q "$root" "$tmp/up"
  (cd "$tmp/up" && find lists -type f -exec sed -i.bak 's/^# Generated: .*/# Generated: 2000-01-01/' {} + &&
    find lists -name '*.bak' -delete && "${G[@]}" commit -qam "lists of 1 Jan 2000")
  git clone -q "$tmp/up" "$tmp/inst"
  (INSTALL_DIR=$tmp/inst PIHOLE_CONTAINER=pihole SKIP_PIHOLE=${1:-0}
    eval "$(fn write_update_script)"
    write_update_script) >/dev/null
  printf 'BOT_TOKEN=1:fake\nCHAT_ID=1\n' >"$tmp/inst/.telegram"
  node "$tmp/inst/generate-lists.js" >/dev/null
  (cd "$tmp/up" && sed -i.bak 's/^# Generated: .*/# Generated: 2000-01-08/' lists/blocklist-all.pihole.txt &&
    rm lists/*.bak && "${G[@]}" commit -qam "lists of 8 Jan 2000")
}
# update [CONTAINERS] - runs the generated update script, prints its exit code
update() {
  (cd "$tmp" && PATH="$bin:$PATH" FAKE_CONTAINERS="${1:-}" bash "$tmp/inst/update-pi5.sh") >"$log/out" 2>&1
  echo $?
}
head_of() { git -C "$1" rev-parse HEAD; }

echo "update script, second week"
fresh
same "local lists differ from upstream before the update" "$(git -C "$tmp/inst" status --porcelain lists/ | grep -c .)" "$(git -C "$tmp/inst" ls-files lists/ | grep -c .)"
same "the update runs through" "$(update pihole)" 0
same "  ... and is on upstream's commit" "$(head_of "$tmp/inst")" "$(head_of "$tmp/up")"
has "  ... and reports on Telegram" "$log/curl.log" "Blocklist updated"
has "a Pi-hole in Docker gets its gravity refreshed" "$log/docker.log" "exec pihole pihole -g"
has "  ... and the message says so" "$log/curl.log" "Pi-hole gravity refreshed"

echo "update script, no Pi-hole"
fresh
same "the update runs through" "$(update)" 0
has "  ... and says that gravity was not refreshed" "$log/curl.log" "No Pi-hole found"
lacks "  ... without calling docker exec" "$log/docker.log" "exec"

echo "update script, SKIP_PIHOLE=1 at setup"
fresh 1
same "the update runs through" "$(update pihole)" 0
lacks "  ... and leaves Pi-hole alone" "$log/docker.log" "exec"
lacks "  ... without a warning about it" "$log/curl.log" "No Pi-hole found"

echo "update script, a step fails"
fresh
git -C "$tmp/inst" remote set-url origin "$tmp/gone"
rc=$(update pihole)
same "a failing pull ends the update with an error" "$([ "$rc" != 0 ] && echo error || echo "rc 0")" error
has "  ... and Telegram is told" "$log/curl.log" "Blocklist update failed"

echo "update script, empty list before the update"
fresh
grep '^#' "$tmp/inst/lists/blocklist-all.pihole.txt" >"$tmp/header" && cp "$tmp/header" "$tmp/inst/lists/blocklist-all.pihole.txt"
same "a list without domains is counted as 0, not '0 0'" "$(update)" 0

echo "the generated script itself"
fresh
script=$tmp/inst/update-pi5.sh
has "the container name of the setup run is written in" "$script" 'PIHOLE_CONTAINER="${PIHOLE_CONTAINER:-pihole}"'
lacks "  ... and no placeholder is left" "$script" "@"
if command -v shellcheck >/dev/null; then
  if shellcheck "$script" >"$log/sc" 2>&1; then ok_ "it passes shellcheck"; else fail_ "it passes shellcheck" "$(head -5 "$log/sc")"; fi
fi

echo "setup: repository update"
fresh
(INSTALL_DIR=$tmp/inst; eval "$(fn setup_repo)"; setup_repo) >"$log/out" 2>&1
same "running setup again over regenerated lists works" "$(head_of "$tmp/inst")" "$(head_of "$tmp/up")"

echo "setup: Node.js"
node_case() { # VERSION - runs install_node with "node --version" = VERSION
  rm -rf "$log" && mkdir -p "$log"
  (PATH="$tmp/fakenode:$bin:$PATH"; export FAKE_NODE_VERSION=$1; eval "$(fn install_node)"; install_node) >"$log/out" 2>&1
}
node_case v20.19.0
has "Node 20 (end of life) is replaced by Node 24" "$log/curl.log" "setup_24.x"
node_case v22.12.0
lacks "Node 22 (still supported) is kept" "$log/curl.log" "nodesource"

echo "setup: Pi-hole"
pihole_case() { # CONTAINERS
  rm -rf "$log" && mkdir -p "$log"
  (PATH="$bin:$PATH" INSTALL_DIR=$tmp/inst SKIP_PIHOLE=0 PIHOLE_CONTAINER=pihole
    export FAKE_CONTAINERS=$1
    eval "$(fn pihole_container_running)"; eval "$(fn configure_pihole)"; configure_pihole) >"$log/out" 2>&1
}
pihole_case pihole
has "a Pi-hole in Docker gets the list by URL" "$log/docker.log" "exec pihole pihole-FTL sqlite3 /etc/pihole/gravity.db"
has "  ... as the published list" "$log/docker.log" "$LIST_URL"
has "  ... without failing on an existing entry" "$log/docker.log" "INSERT OR IGNORE"
has "  ... and gravity is refreshed" "$log/docker.log" "exec pihole pihole -g"
pihole_case ""
has "no Pi-hole at all: a warning" "$log/out" "Pi-hole not found"

echo "setup: Telegram bot service"
rm -rf "$log" && mkdir -p "$log" && rm -f "$tmp/inst/.telegram"
(PATH="$bin:$PATH" INSTALL_DIR=$tmp/inst; eval "$(fn install_bot_service)"; install_bot_service) >"$log/out" 2>&1
has "without Telegram the bot is not installed" "$log/out" "bot service skipped"
lacks "  ... and systemd is not touched" "$log/systemctl.log" "enable"

printf '\n%d passed, %d failed\n' "$pass" "$nfail"
[ "$nfail" -eq 0 ]
